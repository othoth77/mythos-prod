#!/usr/bin/env bash
# =====================================================
# MYTHOS HADDAD — HAD-3: OTH MCP on Haddad, setup (idempotent, no root)
# projects/mythos-haddad/bin/haddad-mcp-setup.sh
#
# Installs NOTHING new. It configures the existing OTH MCP server
# (projects/oth-mcp/server.js — the exact file the VPS runs, unchanged) to
# run on this machine over SSH-stdio, the way the VPS runs it. Three files,
# all user-level, all in the owner's home:
#
#   ~/.local/bin/haddad-mcp-stdio.sh           launcher (from bin/, @REPO@ filled)
#   ~/.config/mythos-haddad/mcp.env            upstream configuration, 0600, NO secret
#   ~/.config/mythos-ai-executor/executor.env  the executor's own bearer — created
#                                              ONLY if absent, with the executor's own
#                                              idiom (projects/mythos-ai-executor/
#                                              deploy/install.sh step 1). The executor
#                                              reads it at start; see the note printed.
#
# What each of the 8 tools resolves to on Haddad (see docs/HADDAD_MCP.md):
#   execution_status / execution_report / budget_status
#                      -> Haddad's own executor, 127.0.0.1:8130 (HAD-3 worker)
#   project_context / capability_registry
#                      -> OTHMODE's public read model (auth:false by its own route
#                         table; there is no OTHMODE on Haddad and building one is
#                         forbidden). Override: HADDAD_MCP_OTHMODE_URL.
#   system_health      -> Status Center (public, server default)
#   haddad_health      -> Haddad's own health report (bin/haddad-health.js, written by
#                         its timer): OS, GPU, AI runtime + model, worker, MCP. This
#                         tool exists ONLY where OTH_MCP_HADDAD_HEALTH_FILE is set —
#                         the VPS keeps its 8 tools.
#   knowledge_search / knowledge_get
#                      -> UNCONFIGURED by design (owner decision (a), 2026-09-23: one
#                      canonical OTHKM store on the VPS, none here). The server
#                         answers UPSTREAM_UNCONFIGURED naming the owner; it never
#                         guesses.
#
# No systemd unit: stdio servers are spawned per client by SSH (VPS precedent).
# No port. No firewall change. No sudo.
#
# Rollback: rm ~/.local/bin/haddad-mcp-stdio.sh ~/.config/mythos-haddad/mcp.env
# (executor.env is the executor's; leave it unless the executor API is unwanted).
# =====================================================
set -euo pipefail

HADDAD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="${HADDAD_MCP_REPO:-$(cd "$HADDAD_DIR/../.." && pwd)}"
CONFIG_DIR="${HADDAD_MCP_CONFIG_DIR:-$HOME/.config/mythos-haddad}"
STATE_DIR="${HADDAD_STATE_DIR:-$HOME/.local/state/mythos-haddad}"
BIN_DIR="${HADDAD_MCP_BIN_DIR:-$HOME/.local/bin}"
EXEC_CFG_DIR="${HADDAD_MCP_EXECUTOR_CONFIG_DIR:-$HOME/.config/mythos-ai-executor}"
EXEC_ENV="$EXEC_CFG_DIR/executor.env"
OTHMODE_URL="${HADDAD_MCP_OTHMODE_URL:-https://othmode.mythosprod.xyz}"
EXECUTOR_URL="${HADDAD_MCP_EXECUTOR_URL:-http://127.0.0.1:8130}"
say() { printf '[haddad-mcp-setup] %s\n' "$*"; }

for c in node sed; do command -v "$c" >/dev/null || { say "MISSING: $c"; exit 1; }; done
[ -f "$REPO/projects/oth-mcp/server.js" ] || { say "MISSING: $REPO/projects/oth-mcp/server.js (wrong checkout? set HADDAD_MCP_REPO)"; exit 1; }
node --check "$REPO/projects/oth-mcp/server.js"

say "1/4 directories"
mkdir -p "$CONFIG_DIR" "$BIN_DIR" "$EXEC_CFG_DIR"
chmod 700 "$CONFIG_DIR" "$EXEC_CFG_DIR"

say "2/4 executor bearer (the executor's own file; value never shown)"
if [ ! -f "$EXEC_ENV" ] || ! grep -q '^MYTHOS_EXECUTOR_TOKEN=' "$EXEC_ENV"; then
  ( umask 077; printf 'MYTHOS_EXECUTOR_TOKEN=%s\n' "$(head -c 32 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 48)" > "$EXEC_ENV" )
  EXEC_TOKEN_NEW=1
else
  EXEC_TOKEN_NEW=0
  say "  already provisioned — keeping it"
fi
chmod 600 "$EXEC_ENV"

say "3/4 upstream configuration (no secret inside)"
ENV_FILE="$CONFIG_DIR/mcp.env"
( umask 077; cat > "$ENV_FILE" <<ENV
# Generated by haddad-mcp-setup.sh — OTH MCP upstreams as seen from Haddad.
# Contains NO secret: the executor bearer is read by reference at launch
# from the executor's own 0600 file (see haddad-mcp-stdio.sh).
OTH_MCP_EXECUTOR_URL=$EXECUTOR_URL
OTH_MCP_EXECUTOR_TOKEN_FILE=$EXEC_ENV
OTH_MCP_OTHMODE_URL=$OTHMODE_URL
# Haddad's own measured state (haddad-health.js report) -> tool haddad_health.
OTH_MCP_HADDAD_HEALTH_FILE=$STATE_DIR/health-latest.json
# OTH_MCP_STATUS_URL: server default (public Status Center).
# OTH_MCP_KNOWLEDGE_URL / _TOKEN: deliberately unset, permanently (owner decision (a)) — the
# knowledge tools answer UPSTREAM_UNCONFIGURED, never a guess.
ENV
)
chmod 600 "$ENV_FILE"
say "  $ENV_FILE"

say "4/4 launcher"
LAUNCHER="$BIN_DIR/haddad-mcp-stdio.sh"
sed -e "s|@REPO@|$REPO|g" "$HADDAD_DIR/bin/haddad-mcp-stdio.sh" > "$LAUNCHER"
chmod 750 "$LAUNCHER"
bash -n "$LAUNCHER"
say "  $LAUNCHER -> $REPO/projects/oth-mcp/server.js"

# Real handshake through the installed launcher, exactly as a client does,
# via the existing MYTHOS MCP client (bin/haddad-mcp-probe.js).
say "verify: initialize + tools/list through $LAUNCHER"
[ -s "$STATE_DIR/health-latest.json" ] || say "  note: no health report yet at $STATE_DIR/health-latest.json — haddad_health answers UNREACHABLE until bin/haddad-health.js runs"
TOOLS="$(HADDAD_MCP_CONFIG_DIR="$CONFIG_DIR" node "$HADDAD_DIR/bin/haddad-mcp-probe.js" "$LAUNCHER" \
  | node -e 'let b="";process.stdin.on("data",d=>b+=d).on("end",()=>{const r=JSON.parse(b);process.stdout.write(String(r.ok?r.tools.length:0))})')"
[ "$TOOLS" = "9" ] || { say "FAIL: expected 9 tools, got '$TOOLS'"; exit 1; }
say "  OK — 9 tools listed (8 shared + haddad_health)"

cat <<NOTE

[haddad-mcp-setup] done.
Client:   ssh $(id -un)@<haddad tailnet address> $LAUNCHER      (stdio MCP)
Local:    $LAUNCHER   < requests.ndjson
Health:   $HADDAD_DIR/bin/haddad-health.js --quick   (check id: mcp)
Test:     node tests/mythos-haddad-mcp-test.js   ·   node tests/othk-6-mcp-server-test.js
NOTE
if [ "$EXEC_TOKEN_NEW" = 1 ]; then
  cat <<NOTE
NOTE:     a new executor bearer was provisioned in $EXEC_ENV.
          The executor reads it ONLY at start — restart the worker so the
          executor tools stop answering UPSTREAM_401:
            systemctl --user restart mythos-haddad-worker.service
          (do this when no task is RUNNING: curl -s $EXECUTOR_URL/health)
NOTE
fi
