#!/usr/bin/env bash
# =====================================================
# MYTHOS HADDAD — an additional GitHub-bridge INSTANCE for one more project
# projects/mythos-haddad/bin/haddad-bridge-instance-setup.sh
#
# Usage:
#   haddad-bridge-instance-setup.sh <slug> <project> [--enable]
#   e.g. haddad-bridge-instance-setup.sh othk oth-knowledge --enable
#
# Not a second bridge: the SAME bin/mythos-github-bridge and the SAME
# executor store/worker, fed by a second intake. It exists so a project
# other than mythos-haddad can be executed on Haddad while each intake
# waits, claims and records independently (V3.1 cross-project; V3.2
# residual 2 made its cache isolation part of the install instead of a
# hand-edited line). Everything is DERIVED from the main instance's
# ~/.config/mythos-haddad/worker.env; exactly these lines differ:
#
#   MYTHOS_BRIDGE_PROJECT       <project>              (must exist in config/projects.json)
#   MYTHOS_ISSUES_LABEL         mythos:haddad-<slug>   the intake label
#   MYTHOS_ISSUES_LABEL_PREFIX  haddad-<slug>:         status labels (never the
#                               main prefix: setStatusLabel deletes siblings)
#   MYTHOS_BRIDGE_CONTROL_DIR   ~/.local/state/mythos-haddad/control-<slug>
#   MYTHOS_BRIDGE_BRANCH        mythos/control-haddad-<slug>  (local, never pushed)
#   MYTHOS_BRIDGE_HOME          ~/mythos-ai-executor-haddad/bridge-<slug>
#                               OWN claims / lock / fence / events — never the
#                               main instance's `bridge/`
#
# Units: mythos-haddad-bridge-<slug>.{service,timer}, rendered from the
# repository's bridge templates with only the EnvironmentFile and the
# description changed. Idempotent; no root; secrets are never copied (the
# token stays in github-issues.env, referenced by both units).
# =====================================================
set -euo pipefail

SLUG="${1:-}"; PROJECT="${2:-}"; ENABLE="${3:-}"
[[ "$SLUG" =~ ^[a-z][a-z0-9]{1,15}$ ]] || { echo "usage: $0 <slug a-z0-9> <project> [--enable]" >&2; exit 2; }
[ -n "$PROJECT" ] || { echo "usage: $0 <slug> <project> [--enable]" >&2; exit 2; }

HADDAD_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO="${HADDAD_REPO:-$(cd "$HADDAD_DIR/../.." && pwd)}"
CFG_DIR="$HOME/.config/mythos-haddad"
UNIT_DIR="$HOME/.config/systemd/user"
STATE_DIR="$HOME/.local/state/mythos-haddad"
MAIN_ENV="$CFG_DIR/worker.env"
ENV_OUT="$CFG_DIR/worker-$SLUG.env"
CONTROL_DIR="$STATE_DIR/control-$SLUG"
BRANCH="mythos/control-haddad-$SLUG"

say() { printf '%s\n' "$*"; }
fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

[ -f "$MAIN_ENV" ] || fail "main instance not installed ($MAIN_ENV missing) — run haddad-worker-setup.sh first"
node -e 'const p=require(process.argv[1]);if(!p[process.argv[2]])process.exit(1)' \
  "$REPO/projects/mythos-ai-executor/config/projects.json" "$PROJECT" || fail "project '$PROJECT' is not in config/projects.json"
EXEC_HOME="$(sed -n 's/^MYTHOS_EXECUTOR_HOME=//p' "$MAIN_ENV" | tail -1)"
[ -n "$EXEC_HOME" ] || fail "MYTHOS_EXECUTOR_HOME missing from $MAIN_ENV"
BRIDGE_HOME="$EXEC_HOME/bridge-$SLUG"
[ "$BRIDGE_HOME" != "$EXEC_HOME/bridge" ] || fail "refusing to share the main bridge cache"

say "1/4 env $ENV_OUT (derived from worker.env)"
TMP="$(mktemp)"
{
  echo "# Generated by haddad-bridge-instance-setup.sh — bridge instance '$SLUG' for project '$PROJECT'."
  echo "# Derived from worker.env; only the project/label/control/cache lines differ. No secrets."
  grep -v -E '^(MYTHOS_BRIDGE_PROJECT|MYTHOS_ISSUES_LABEL|MYTHOS_ISSUES_LABEL_PREFIX|MYTHOS_BRIDGE_CONTROL_DIR|MYTHOS_BRIDGE_BRANCH|MYTHOS_BRIDGE_HOME)=' "$MAIN_ENV" | grep -v -E '^# Generated by'
  echo "MYTHOS_BRIDGE_PROJECT=$PROJECT"
  echo "MYTHOS_ISSUES_LABEL=mythos:haddad-$SLUG"
  echo "MYTHOS_ISSUES_LABEL_PREFIX=haddad-$SLUG:"
  echo "MYTHOS_BRIDGE_CONTROL_DIR=$CONTROL_DIR"
  echo "MYTHOS_BRIDGE_BRANCH=$BRANCH"
  echo "MYTHOS_BRIDGE_HOME=$BRIDGE_HOME"
} > "$TMP"
install -m 600 "$TMP" "$ENV_OUT"; rm -f "$TMP"
[ "$(grep -c '^MYTHOS_BRIDGE_HOME=' "$ENV_OUT")" = 1 ] || fail "MYTHOS_BRIDGE_HOME must appear exactly once"

say "2/4 cache $BRIDGE_HOME (own claims/lock/fence)"
mkdir -p -m 700 "$BRIDGE_HOME"

say "3/4 control worktree $CONTROL_DIR on $BRANCH (local)"
if [ ! -e "$CONTROL_DIR" ]; then
  git -C "$REPO" rev-parse --verify --quiet "$BRANCH" >/dev/null || git -C "$REPO" branch "$BRANCH" "$(git -C "$REPO" rev-parse HEAD)"
  git -C "$REPO" worktree add "$CONTROL_DIR" "$BRANCH" >/dev/null
fi
mkdir -p "$CONTROL_DIR/control/tasks" "$CONTROL_DIR/control/reports"

say "4/4 units mythos-haddad-bridge-$SLUG.{service,timer}"
mkdir -p "$UNIT_DIR"
sed -e "s|@REPO@|$REPO|g" -e "s|@HADDAD_DIR@|$HADDAD_DIR|g" \
    -e "s|%h/.config/mythos-haddad/worker.env|%h/.config/mythos-haddad/worker-$SLUG.env|" \
    -e "s|^Description=.*|Description=MYTHOS Haddad — GitHub bridge, $PROJECT instance (one tick, mythos:haddad-$SLUG only)|" \
    "$HADDAD_DIR/systemd/mythos-haddad-bridge.service" > "$UNIT_DIR/mythos-haddad-bridge-$SLUG.service"
sed -e "s|mythos-haddad-bridge.service|mythos-haddad-bridge-$SLUG.service|g" \
    -e "s|^Description=.*|Description=MYTHOS Haddad — GitHub bridge tick, $PROJECT instance|" \
    "$HADDAD_DIR/systemd/mythos-haddad-bridge.timer" > "$UNIT_DIR/mythos-haddad-bridge-$SLUG.timer"
grep -q "EnvironmentFile=%h/.config/mythos-haddad/worker-$SLUG.env" "$UNIT_DIR/mythos-haddad-bridge-$SLUG.service" || fail "unit does not use the instance env"
! grep -q "EnvironmentFile=%h/.config/mythos-haddad/worker.env" "$UNIT_DIR/mythos-haddad-bridge-$SLUG.service" || fail "unit still reads the main env"

if [ "$ENABLE" = "--enable" ]; then
  systemctl --user daemon-reload
  systemctl --user enable --now "mythos-haddad-bridge-$SLUG.timer" >/dev/null
  say "  timer: $(systemctl --user is-active "mythos-haddad-bridge-$SLUG.timer")"
fi
say "OK — instance '$SLUG' → project $PROJECT, label mythos:haddad-$SLUG, cache $BRIDGE_HOME"
